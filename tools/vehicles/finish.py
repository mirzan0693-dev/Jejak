"""Downscale raw three.js renders, compress them, write src/vehicleImages.ts and an optional contact sheet.

Usage: python3 -I tools/vehicles/finish.py [contact-sheet.png]
"""
import json
import os
import sys

from PIL import Image

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
out = os.path.join(root, "assets", "vehicles")
meta = json.load(open(os.path.join(out, "index.json")))
W, H = meta["W"], meta["H"]

entries = []
for item in meta["index"]:
    raw = os.path.join(out, item["file"])
    img = Image.open(raw).convert("RGBA").resize((W, H), Image.LANCZOS)
    name = f'{item["kind"]}-{item["style"]}-{item["layer"]}.png'
    # palette + alpha keeps files small; 256 colours is plenty at pin size
    img.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(
        os.path.join(out, name), optimize=True
    )
    os.remove(raw)
    entries.append((item["kind"], item["style"], item["layer"], name))
os.remove(os.path.join(out, "index.json"))

lines = [
    "// Generated by tools/vehicles/finish.py from three.js renders. Do not edit by hand.",
    "/* eslint-disable */",
    "export const VEHICLE_IMAGE_SIZE = { width: %d, height: %d };" % (W, H),
    "export const VEHICLE_IMAGES: Record<string, number> = {",
]
for kind, style, layer, name in entries:
    lines.append(f"  '{kind}/{style}/{layer}': require('../assets/vehicles/{name}'),")
lines.append("};")
open(os.path.join(root, "src", "vehicleImages.ts"), "w").write("\n".join(lines) + "\n")

total = sum(os.path.getsize(os.path.join(out, n)) for *_, n in entries)
print(f"{len(entries)} images, {total / 1024:.0f} KB total")

if len(sys.argv) > 1:
    # contact sheet: each vehicle composed (base under body) on the light map colour, plus a dark row
    order = [("car", s) for s in ["hatchback", "sedan", "suv", "mpv", "pickup"]] + [
        ("motorbike", s) for s in ["scooter", "kapcai", "superbike", "cruiser", "bicycle"]
    ]
    paints = {"car": ["blue", "red", "white", "black", "silver"], "motorbike": ["red", "blue", "green", "yellow", "black"]}
    sheet = Image.new("RGBA", (W * 5 + 60, H * 2 + 40), (237, 234, 227, 255))
    for i, (kind, style) in enumerate(order):
        col, row = i % 5, i // 5
        paint = paints[kind][col]
        base = Image.open(os.path.join(out, f"{kind}-{style}-base.png")).convert("RGBA")
        body = Image.open(os.path.join(out, f"{kind}-{style}-{paint}.png")).convert("RGBA")
        x, y = 10 + col * (W + 10), 10 + row * (H + 20)
        sheet.alpha_composite(base, (x, y))
        sheet.alpha_composite(body, (x, y))
    sheet.save(sys.argv[1])
    print("sheet:", sys.argv[1])
